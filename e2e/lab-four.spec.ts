import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { labFourAssignment, labFourDocumentHash } from "../server/lab-four";

test("published Lab 4 instructions, handout and task selection work for teachers and students", async ({ page }, info) => {
  await page.goto("/");
  await page.getByLabel("Email or student roll number").fill("fixture@example.test");
  await page.getByLabel("Password", { exact: true }).fill("FixtureTeacher2026!");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("button", { name: "Labs", exact: true })).toBeVisible();
  const before = await (await page.request.get("/api/state")).json();
  const assignment = await labFourAssignment();
  assignment.title += ` ${info.project.name} fixture`;
  const created = await page.request.post("/api/labs", { data: assignment });
  expect(created.status()).toBe(201);
  const saved = await created.json();
  const after = await (await page.request.get("/api/state")).json();
  expect(after.submissions).toEqual(before.submissions);
  expect(after.labs.filter((lab: { id: string }) => lab.id !== saved.id)).toEqual(before.labs);
  await page.reload();
  await page.getByRole("button", { name: "Labs", exact: true }).click();
  const card = page.locator("section.minimal-lab").filter({ hasText: assignment.title });
  await expect(card.getByText("Published", { exact: true })).toHaveText("Published");
  await card.getByRole("button", { name: /^Edit Lab / }).click();
  const editor = page.getByRole("dialog").filter({ has: page.getByRole("heading", { name: "Edit lab", exact: true }) });
  await expect(editor.getByLabel("Lab title", { exact: true })).toHaveValue(assignment.title);
  await expect(editor.getByLabel("Task title", { exact: true }).filter({ visible: true })).toHaveValue("University Home Page");
  await editor.getByRole("button", { name: /^Task 2/ }).click();
  await expect(editor.getByLabel("Task title", { exact: true }).filter({ visible: true })).toHaveValue("Student Registration Form");
  await expect(editor.getByRole("textbox", { name: "Task instructions", exact: true })).toHaveValue(/maxlength="20"/);
  await expect(editor.getByLabel("Maximum marks", { exact: true }).filter({ visible: true })).toHaveValue("10");
  await editor.getByRole("button", { name: "Close lab editor", exact: true }).click();

  const login = await page.request.post("/api/auth/login", { data: { email: info.project.name === "desktop" ? "35" : "36", password: "FixtureTeacher2026!" } });
  expect(login.ok()).toBe(true);
  await page.reload();
  const open = page.getByRole("button", { name: new RegExp(`^Open Lab \\d+: ${assignment.title.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}$`) });
  await open.focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("heading", { name: "Task checklist", exact: true })).toBeVisible();
  const tasks = page.locator("details.student-task");
  await expect(tasks).toHaveCount(2);
  const registration = tasks.filter({ hasText: "Student Registration Form" });
  await registration.locator("summary").focus();
  await page.keyboard.press("Enter");
  await expect(registration.locator(".student-instructions")).toContainText('maxlength="20"');
  await expect(page.getByText("No deadline", { exact: true }).first()).toBeVisible();
  const downloading = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download instructions", exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toBe("Web Engineering lab 4.docx");
  expect(createHash("sha256").update(await readFile((await download.path())!)).digest("hex")).toBe(labFourDocumentHash);
  await registration.getByRole("button", { name: "Submit task", exact: true }).click();
  const upload = page.getByRole("dialog", { name: "Submit lab work", exact: true });
  await expect(upload.getByLabel("Choose a task")).toHaveValue("lab4-task2");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
